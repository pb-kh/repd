-- repro.lock.lua I/O (contracts/lockfile.md, research R16). The file is plain
-- Lua data; it is loaded with an empty environment so any code is rejected.
local canon = require("repro.canon")
local err = require("repro.err")

local M = {}

M.HEADER = "-- Generated by repro. Do not edit by hand; use --provider / --reselect.\n"
M.SOURCES = { cli = true, prompt = true, ["only-option"] = true }

local function bad(file, what)
  err.raise("E_CONFIG", file .. ": " .. what, "delete the file or the broken entry; repro will ask again")
end

function M.parse(text, file)
  if text:sub(1, 1) == "\27" then bad(file, "bytecode is not allowed") end
  local chunk, syntax = loadstring(text, "@" .. file)
  if not chunk then bad(file, "syntax error: " .. tostring(syntax)) end
  -- Nested function prototypes mean code, not data.
  if jit and require("jit.util").funcinfo(chunk).children then
    bad(file, "functions are not allowed")
  end
  -- No globals at all: function calls and global access fail.
  setfenv(chunk, setmetatable({}, {
    __index = function(_, k) error("global '" .. tostring(k) .. "' is not allowed", 2) end,
    __newindex = function(_, k) error("assignment to '" .. tostring(k) .. "' is not allowed", 2) end,
  }))
  local ok, value = pcall(chunk)
  if not ok then bad(file, "only literal data is allowed (" .. tostring(value) .. ")") end
  if type(value) ~= "table" then bad(file, "must return a table") end
  for _, k in ipairs(canon.sorted_keys(value)) do
    if k ~= "version" and k ~= "providers" then bad(file, "unknown key '" .. tostring(k) .. "'") end
  end
  if value.version ~= 1 then
    if type(value.version) == "number" and value.version > 1 then
      err.raise("E_CONFIG", file .. " was written by a newer repro (lock version " .. value.version .. ")",
        "upgrade repro")
    end
    bad(file, "version must be 1")
  end
  local providers = value.providers or {}
  if type(providers) ~= "table" then bad(file, "providers must be a table") end
  for _, iface in ipairs(canon.sorted_keys(providers)) do
    local entry = providers[iface]
    if type(iface) ~= "string" or type(entry) ~= "table" or type(entry.provider) ~= "string"
        or type(entry.source) ~= "string" then
      bad(file, "malformed entry for " .. tostring(iface))
    end
    for _, k in ipairs(type(entry) == "table" and canon.sorted_keys(entry) or {}) do
      if k ~= "provider" and k ~= "source" and k ~= "decided_at" then
        bad(file, "unknown field '" .. tostring(k) .. "' in entry " .. iface)
      end
    end
  end
  value.providers = providers
  return value
end

function M.serialize(lock)
  return M.HEADER .. "return " .. canon.pretty(lock) .. "\n"
end

return M
