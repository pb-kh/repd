-- repro.lock.lua parse/serialise (contracts/lockfile.md).
local lu = require("luaunit")
local lock = require("repro.lock")
local err = require("repro.err")

local function expect(code, fn, ...)
  local ok, e = pcall(fn, ...)
  lu.assertFalse(ok)
  lu.assertTrue(err.is(e), tostring(e))
  lu.assertEquals(e.code, code)
  return e
end

TestLock = {}

local SAMPLE = {
  version = 1,
  providers = {
    ["dev/ide"] = { provider = "dev/ide/vim", source = "prompt", decided_at = "2026-10-09T12:00:00Z" },
    ["dev/shell"] = { provider = "dev/shell/zsh", source = "cli", decided_at = "2026-10-09T12:00:01Z" },
  },
}

function TestLock.test_serialize_format()
  local text = lock.serialize(SAMPLE)
  lu.assertEquals(text, table.concat({
    "-- Generated by repro. Do not edit by hand; use --provider / --reselect.",
    "return {",
    "  providers = {",
    '    ["dev/ide"] = {',
    '      decided_at = "2026-10-09T12:00:00Z",',
    '      provider = "dev/ide/vim",',
    '      source = "prompt",',
    "    },",
    '    ["dev/shell"] = {',
    '      decided_at = "2026-10-09T12:00:01Z",',
    '      provider = "dev/shell/zsh",',
    '      source = "cli",',
    "    },",
    "  },",
    "  version = 1,",
    "}",
    "",
  }, "\n"))
end

function TestLock.test_round_trip()
  lu.assertEquals(lock.parse(lock.serialize(SAMPLE), "repro.lock.lua"), SAMPLE)
end

function TestLock.test_empty_lock()
  local text = lock.serialize({ version = 1, providers = {} })
  lu.assertEquals(lock.parse(text, "x"), { version = 1, providers = {} })
end

function TestLock.test_rejects_code()
  expect("E_CONFIG", lock.parse, "return { version = 1, providers = os.exit() }", "repro.lock.lua")
  expect("E_CONFIG", lock.parse, "x = 1 return { version = 1, providers = {} }", "repro.lock.lua")
  expect("E_CONFIG", lock.parse, "return {", "repro.lock.lua")
  expect("E_CONFIG", lock.parse, "return (function() return {version=1,providers={}} end)()", "repro.lock.lua")
end

function TestLock.test_rejects_bad_shape()
  local e = expect("E_CONFIG", lock.parse, "return { version = 2, providers = {} }", "repro.lock.lua")
  lu.assertStrContains(e.hint, "upgrade repro")
  expect("E_CONFIG", lock.parse, "return { version = 1, providers = {}, extra = 1 }", "repro.lock.lua")
  expect("E_CONFIG", lock.parse, "return { version = 1, providers = { x = { provider = 1 } } }", "repro.lock.lua")
end

os.exit(lu.LuaUnit.run())
